#!/bin/bash
# Builds a .deb that bundles the app and its Python dependencies under
# /opt/handcue. MediaPipe and PySide6 are not packaged by Debian or Ubuntu,
# so they come from PyPI, pinned by hash in requirements.lock.
#
# The bundle is tied to the Python version of the system it is built on, so build
# it on the release you target (CI builds one for Debian 13 and one for Ubuntu 24.04).
#
# Usage, from the repository root:  packaging/deb/build.sh [suffix]
# Needs: python3-venv, dpkg-dev. The .deb is written to dist/.
set -euo pipefail
umask 022  # files in the package must not be group-writable

APP_ID=io.github.ignacio_aranda.HandCue
SUFFIX=${1:-}
VERSION=$(sed -n 's/^__version__ = "\(.*\)"/\1/p' src/handcue/__init__.py)
ARCH=$(dpkg --print-architecture)
PY=$(python3 -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')
PREFIX=/opt/handcue

stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT
root="$stage/root"
venv="$root$PREFIX"

echo "==> Building the wheel"
python3 -m venv "$stage/build-env"
"$stage/build-env/bin/pip" install --quiet build
"$stage/build-env/bin/python" -m build --wheel --outdir "$stage/wheel" .

echo "==> Installing into $PREFIX (Python $PY)"
python3 -m venv "$venv"
"$venv/bin/pip" install --quiet --no-cache-dir --require-hashes -r requirements.lock
"$venv/bin/pip" install --quiet --no-cache-dir --no-deps "$stage"/wheel/*.whl
"$venv/bin/pip" uninstall --quiet --yes pip
# Pin the interpreter to the exact version the dependencies were installed for, so a
# newer default python3 on the system does not break the bundle.
ln -sf "/usr/bin/python$PY" "$venv/bin/python3"
# Scripts generated by venv and pip embed the build path; the launcher below runs
# the bundled interpreter directly instead.
find "$venv/bin" -type f ! -name 'python*' -delete
find "$venv" -name '__pycache__' -type d -prune -exec rm -rf {} +
# Bytecode is precompiled because /opt is read-only at runtime. Some bundled files are
# templates or test data rather than Python, so compile errors are expected and ignored.
"$venv/bin/python" -m compileall -q -s "$root" -p / "$venv/lib" > /dev/null || true

echo "==> Desktop integration"
install -Dm755 /dev/stdin "$root/usr/bin/handcue" <<EOF
#!/bin/sh
exec $PREFIX/bin/python -m handcue "\$@"
EOF
install -Dm644 "data/$APP_ID.desktop" "$root/usr/share/applications/$APP_ID.desktop"
install -Dm644 "data/$APP_ID.metainfo.xml" "$root/usr/share/metainfo/$APP_ID.metainfo.xml"
install -Dm644 src/handcue/resources/icon.svg "$root/usr/share/icons/hicolor/scalable/apps/$APP_ID.svg"
install -Dm644 LICENSE "$root/usr/share/doc/handcue/copyright"

echo "==> Package metadata"
mkdir -p "$root/DEBIAN"
size=$(du -sk "$root" | cut -f1)
cat > "$root/DEBIAN/control" <<EOF
Package: handcue
Version: $VERSION
Architecture: $ARCH
Maintainer: Ignacio Aranda <92518274+Ignacio-Aranda@users.noreply.github.com>
Installed-Size: $size
Depends: python$PY, libgl1, libegl1, libglib2.0-0, libfontconfig1, libdbus-1-3, libxkbcommon0, libxkbcommon-x11-0, libxcb-cursor0
Recommends: wireplumber, xdg-utils, xdg-desktop-portal
Suggests: v4l2loopback-dkms
Section: video
Priority: optional
Homepage: https://github.com/Ignacio-Aranda/handcue
Description: Control your computer with gestures from your webcam
 Recognizes hand, face and body gestures and turns them into actions: media
 keys, apps, websites, shortcuts, typing and a virtual mouse. Includes webcam
 controls, face recognition and a virtual camera with background effects.
 Everything runs locally.
EOF

mkdir -p dist
out="dist/handcue_${VERSION}${SUFFIX:+_$SUFFIX}_${ARCH}.deb"
dpkg-deb --root-owner-group --build "$root" "$out"
echo "Built $out"
